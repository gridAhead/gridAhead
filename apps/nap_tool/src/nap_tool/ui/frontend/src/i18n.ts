const formattedMessages = Object.entries(messages)
  .filter(([source]) => /\{\d+\}/.test(source))
  .map(([source, target]) => {
    const indexes: number[] = []
    const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    const pattern = escaped.replace(/\\\{(\d+)\\\}/g, (_, index) => {
      indexes.push(Number(index))
      return '(.+?)'
    })
    return { pattern: new RegExp('^' + pattern + '$'), indexes, target }
  })

function germanMessage(source: string): string {
  if (Object.hasOwn(messages, source)) return messages[source]
  for (const { pattern, indexes, target } of formattedMessages) {
    const match = source.match(pattern)
    if (!match) continue
    return target.replace(/\{(\d+)\}/g, (placeholder, index) => {
      const position = indexes.indexOf(Number(index))
      return position < 0 ? placeholder : match[position + 1]
    })
  }
  return source
}

export function t(value: string | null | undefined, ...values: unknown[]): string {
  const source = value ?? ''
  const text = locale === 'de' ? germanMessage(source) : source
  return text.replace(/\{(\d+)\}/g, (placeholder, index) => Number(index) < values.length ? String(values[Number(index)]) : placeholder)
}

export const translate = t

export function startLocalization(): void {
  document.documentElement.lang = locale
  const confirm = window.confirm.bind(window)
  window.confirm = (message) => confirm(t(message ?? ''))
  const prompt = window.prompt.bind(window)
  window.prompt = (message, defaultValue) => prompt(t(message ?? ''), defaultValue)
  const alert = window.alert.bind(window)
  window.alert = (message) => alert(t(message ?? ''))
}
